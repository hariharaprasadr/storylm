#!/usr/bin/env python3
"""StoryLM Unified CLI: Generate stories, test KV-cache, serve the web visualizer, or inspect the model."""
from __future__ import annotations

import argparse
import http.server
import os
import socketserver
import subprocess
import sys
import webbrowser

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)


def cmd_story(args):
    """Run interactive story generation."""
    cmd = [sys.executable, os.path.join(ROOT, "storylm/story.py")]
    if args.world:
        cmd.extend(["--world", args.world])
    if args.mode:
        cmd.extend(["--mode", args.mode])
    if args.place:
        cmd.extend(["--place", args.place])
    if args.theme:
        cmd.extend(["--theme", args.theme])
    if args.seed is not None:
        cmd.extend(["--seed", str(args.seed)])
    if args.temperature is not None:
        cmd.extend(["--temperature", str(args.temperature)])
    if args.checkpoint:
        cmd.extend(["--checkpoint", args.checkpoint])
    if args.vocab:
        cmd.extend(["--vocab", args.vocab])
    if args.raw:
        cmd.append("--raw")
    if args.list:
        cmd.append("--list")
    return subprocess.run(cmd, cwd=ROOT).returncode


def cmd_test(args):
    """Run KV-cache equivalence and speed benchmark test."""
    cmd = [sys.executable, os.path.join(ROOT, "storylm/test_cache.py")]
    if args.checkpoint:
        cmd.extend(["--checkpoint", args.checkpoint])
    if args.vocab:
        cmd.extend(["--vocab", args.vocab])
    return subprocess.run(cmd, cwd=ROOT).returncode


def cmd_audit(args):
    """Audit a checkpoint for overfitting / memorisation of the training corpus."""
    cmd = [sys.executable, os.path.join(ROOT, "training/memorisation.py")]
    if args.checkpoint:
        cmd.extend(["--checkpoint", args.checkpoint])
    if args.corpus:
        cmd.extend(["--corpus", args.corpus])
    if args.packed:
        cmd.extend(["--packed", args.packed])
    if args.vocab:
        cmd.extend(["--vocab", args.vocab])
    if args.stories is not None:
        cmd.extend(["--stories", str(args.stories)])
    if args.repeats is not None:
        cmd.extend(["--repeats", str(args.repeats)])
    return subprocess.run(cmd, cwd=ROOT).returncode



def cmd_web(args):
    """Serve the interactive web explainer and open in browser."""
    port = args.port
    web_dir = os.path.join(ROOT, "web")
    os.chdir(web_dir)

    class Handler(http.server.SimpleHTTPRequestHandler):
        def log_message(self, format, *args):
            pass  # quiet logging

        def end_headers(self):
            # story_data.js is regenerated by export_story.py, so let the browser
            # revalidate: without this the page keeps running the old weights.
            self.send_header("Cache-Control", "no-cache")
            super().end_headers()

    try:
        with socketserver.TCPServer(("", port), Handler) as httpd:
            url = f"http://localhost:{port}/index.html"
            print(f"Serving StoryLM Web Explainer at {url}")
            print("Press Ctrl+C to stop.")
            if not args.no_browser:
                webbrowser.open(url)
            httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nServer stopped.")
        return 0


def cmd_info(args):
    """Print the token tables, each checkpoint's own table, and the datasets."""
    from storylm.vocab import (GENERATIONS, TableMismatch, checkpoint_meta,
                               default_checkpoint, size_of, table_for_checkpoint)

    print("=" * 72)
    print("  StoryLM - Tiny Language Model")
    print("=" * 72)
    print("Token tables (data/):")
    for generation in GENERATIONS:
        if os.path.exists(generation.vocab_path()):
            print(f"  {generation.name:<3} {generation.vocab:<20} "
                  f"{size_of(generation.vocab_path()):>5} ids   series {generation.series}")

    ckpt_dir = os.path.join(ROOT, "checkpoints")
    print("\nCheckpoints:")
    default = default_checkpoint()
    for name in sorted(os.listdir(ckpt_dir)) if os.path.isdir(ckpt_dir) else []:
        if not name.endswith(".pt"):
            continue
        path = os.path.join(ckpt_dir, name)
        size_mb = os.path.getsize(path) / (1024 * 1024)
        mark = "*" if path == default else " "
        try:
            vocab_size, _ = checkpoint_meta(path)
            _, generation = table_for_checkpoint(path)
            note = f"pairs with {generation.name} ({generation.vocab})"
        except TableMismatch as error:
            vocab_size = 0
            note = "UNPAIRED: " + str(error).splitlines()[0]
        print(f" {mark}checkpoints/{name:<22} {size_mb:>5.2f} MB  "
              f"{vocab_size:>4} ids  {note}")
    if default:
        print(f"\n* = default for `cli.py story`/`test`/`audit`")

    data_dir = os.path.join(ROOT, "data/processed")
    if os.path.exists(data_dir):
        print("\nDatasets:")
        for item in sorted(os.listdir(data_dir)):
            full = os.path.join(data_dir, item)
            if os.path.isfile(full):
                size_mb = os.path.getsize(full) / (1024 * 1024)
                print(f"  - {item:<20} {size_mb:>8.2f} MB")
            else:
                print(f"  - {item + '/':<20} (directory)")
    print("=" * 72)
    return 0


def main():
    parser = argparse.ArgumentParser(description="StoryLM: Tiny Model CLI & Web Visualizer")
    subparsers = parser.add_subparsers(dest="subcommand", help="Available subcommands")

    # story
    p_story = subparsers.add_parser("story", aliases=["generate"], help="Generate a character story")
    p_story.add_argument("--world", default="bluey", help="World: bluey, gabby, one, amelia, junie")
    p_story.add_argument("--mode", default="bedtime", help="Mode: bedtime, adventure, funny, kindness, mystery, discovery, celebration, silly")
    p_story.add_argument("--place", default=None, help="Place inside chosen world")
    p_story.add_argument("--theme", default="help", help="Theme: help, share, brave, try, honesty, curiosity, patience, friendship, creativity")
    p_story.add_argument("--seed", type=int, default=0, help="Random seed for sampling")
    p_story.add_argument("--temperature", type=float, default=0.8, help="Sampling temperature")
    p_story.add_argument("--checkpoint", default=None, help="Path to .pt checkpoint")
    p_story.add_argument("--vocab", default=None,
                         help="Token table (default: the one the checkpoint was trained on)")
    p_story.add_argument("--raw", action="store_true", help="Print raw draft tokens")
    p_story.add_argument("--list", action="store_true", help="List available characters & places")

    # test
    p_test = subparsers.add_parser("test", help="Verify KV-cache equivalence & latency")
    p_test.add_argument("--checkpoint", default=None)
    p_test.add_argument("--vocab", default=None,
                        help="Token table (default: the one the checkpoint was trained on)")

    # audit
    p_audit = subparsers.add_parser("audit", help="Check a checkpoint for overfitting / memorisation")
    p_audit.add_argument("--checkpoint", default=None, help="Path to .pt checkpoint")
    p_audit.add_argument("--corpus", default=None, help="Training corpus .jsonl to compare against")
    p_audit.add_argument("--packed", default=None, help="Packed .npz holding the loss split")
    p_audit.add_argument("--vocab", default=None, help="Token table (default: the checkpoint's own)")
    p_audit.add_argument("--stories", type=int, default=None, help="Stories to generate (default: 100)")
    p_audit.add_argument("--repeats", type=int, default=None, help="Stories per prompt (default: 5)")

    # web
    p_web = subparsers.add_parser("web", help="Start local server for interactive web visualizer")
    p_web.add_argument("--port", type=int, default=8000, help="Port to serve on (default: 8000)")
    p_web.add_argument("--no-browser", action="store_true", help="Do not automatically open browser")

    # info
    subparsers.add_parser("info", help="Print model and dataset summary")

    args = parser.parse_args()
    if args.subcommand in ("story", "generate"):
        return cmd_story(args)
    elif args.subcommand == "test":
        return cmd_test(args)
    elif args.subcommand == "audit":
        return cmd_audit(args)
    elif args.subcommand == "web":
        return cmd_web(args)
    elif args.subcommand == "info":
        return cmd_info(args)
    else:
        parser.print_help()
        return 0


if __name__ == "__main__":
    sys.exit(main())
