#!/usr/bin/env python3
"""Export the full TinyLM weights + prompt metadata so the web page can run
story generation live in the browser (no server, file:// safe).

Output: ``window.STORY = {...}`` in web/story_data.js, mirroring
``window.TRACE`` from export_trace.py. Weights are stored as base64 of
little-endian float16, decoded by web/story.js at page load (~3.4 MB).
"""
from __future__ import annotations

import argparse
import base64
import json
import os

import numpy as np
import torch

from tinylm.model import Config, TinyLM

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

MODES = ["adventure", "bedtime", "funny", "kindness"]
THEMES = ["help", "share", "brave", "try"]


def b64_f16(tensor):
    arr = tensor.detach().cpu().numpy().astype("<f2")  # little-endian float16
    return base64.b64encode(arr.tobytes()).decode("ascii")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--checkpoint", default=os.path.join(ROOT, "checkpoints/embedded_big.pt"))
    ap.add_argument("--out", default=os.path.join(ROOT, "web/story_data.js"))
    args = ap.parse_args()

    ckpt = torch.load(args.checkpoint, weights_only=False, map_location="cpu")
    cfg = Config(**ckpt["config"])
    model = TinyLM(cfg)
    model.load_state_dict(ckpt["model"])
    print(f"loaded {args.checkpoint}: {sum(p.numel() for p in model.parameters()):,} params")

    weights = {}
    seen = set()
    for name, p in model.named_parameters():
        if name == "head.weight":
            continue  # tied with embed.weight
        weights[name] = b64_f16(p)
        seen.add(name)
    print(f"exported {len(weights)} tensors")

    vocab = json.load(open(os.path.join(ROOT, "data/vocab.json")))["tokens"]
    series = json.load(open(os.path.join(ROOT, "data/series.json")))
    worlds = [
        {
            "id": entry["id"],
            "name": entry["story_name"],
            "token": entry["token"],
            "description": entry["description"],
            "places": entry["places"],
            "modes": [m for m in MODES if m in entry["modes"]],
            "proper_names": sorted({entry["story_name"].lower()}
                                   | {f.lower() for f in entry["friends"]}),
        }
        for entry in series
    ]

    payload = {
        "checkpoint": os.path.relpath(args.checkpoint, ROOT),
        "config": {
            "vocab": cfg.vocab, "ctx": cfg.ctx, "layers": cfg.layers,
            "d_model": cfg.d_model, "heads": cfg.heads,
            "head_dim": cfg.head_dim, "ffn": cfg.ffn,
        },
        "sampling": {"temperature": 0.8, "top_k": 40,
                     "max_lines": 26, "resample_tries": 3, "max_new_tokens": 80},
        "vocab": vocab,
        "worlds": worlds,
        "themes": THEMES,
        "weights": weights,
    }

    blob = json.dumps(payload, separators=(",", ":"))
    with open(args.out, "w") as handle:
        handle.write("// Generated by training/export_story.py - do not edit by hand.\n")
        handle.write(f"window.STORY = {blob};\n")
    size = os.path.getsize(args.out)
    print(f"wrote {args.out} ({size / 1024 / 1024:.1f} MB)")


if __name__ == "__main__":
    main()
