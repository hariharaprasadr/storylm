#!/usr/bin/env python3
"""Export the full StoryLM weights + prompt metadata so the web page can run
story generation live in the browser (no server, file:// safe).

Output: ``window.STORY = {...}`` in web/story_data.js. Weights are stored
as base64 of little-endian float16, decoded by web/story.js at page load
(~3.4 MB). This file is the single source of truth for the whole site:
Story Studio generates from it, and web/wt-trace.js computes every number
the walkthrough shows straight from these weights.
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import sys

import torch

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from storylm.model import Config, StoryLM
from storylm.vocab import (TableMismatch, control_values, default_checkpoint,
                           series_of, table_for_checkpoint)


def b64_f16(tensor):
    arr = tensor.detach().cpu().numpy().astype("<f2")  # little-endian float16
    return base64.b64encode(arr.tobytes()).decode("ascii")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--checkpoint", default=None,
                    help="checkpoint to export (default: the newest in checkpoints/)")
    ap.add_argument("--vocab", default=None,
                    help="token table (default: the one the checkpoint was trained on)")
    ap.add_argument("--out", default=os.path.join(ROOT, "web/story_data.js"))
    args = ap.parse_args()

    checkpoint = args.checkpoint or default_checkpoint()
    if checkpoint is None or not os.path.exists(checkpoint):
        print("no checkpoint found; train one first (see training/README.md)", file=sys.stderr)
        return 2
    try:
        tokens, generation = table_for_checkpoint(checkpoint, args.vocab)
    except TableMismatch as error:
        print(error, file=sys.stderr)
        return 2

    ckpt = torch.load(checkpoint, weights_only=False, map_location="cpu")
    cfg = Config(**ckpt["config"])
    model = StoryLM(cfg)
    model.load_state_dict(ckpt["model"])
    print(f"loaded {checkpoint}: {sum(p.numel() for p in model.parameters()):,} params"
          f"  [{generation.name} table: {generation.vocab}]")

    weights = {}
    seen = set()
    for name, p in model.named_parameters():
        if name == "head.weight":
            continue  # tied with embed.weight
        weights[name] = b64_f16(p)
        seen.add(name)
    print(f"exported {len(weights)} tensors")

    vocab = tokens
    series = series_of(generation.series_path())
    MODES = control_values(vocab, "MODE")
    THEMES = control_values(vocab, "THEME")
    worlds = [
        {
            "id": entry["id"],
            "name": entry["story_name"],
            "token": entry["token"],
            "description": entry["description"],
            "places": entry["places"],
            "modes": [m for m in MODES if m in entry["modes"]],
            "proper_names": sorted({entry["story_name"].lower()}
                                   | {f.lower() for f in entry["friends"]}),
        }
        for entry in series
    ]

    payload = {
        "checkpoint": os.path.relpath(checkpoint, ROOT),
        "config": {
            "vocab": cfg.vocab, "ctx": cfg.ctx, "layers": cfg.layers,
            "d_model": cfg.d_model, "heads": cfg.heads,
            "head_dim": cfg.head_dim, "ffn": cfg.ffn,
        },
        "sampling": {"temperature": 0.8, "top_k": 40,
                     "max_lines": 26, "resample_tries": 3, "max_new_tokens": 80},
        "vocab": vocab,
        "worlds": worlds,
        "modes": MODES,
        "themes": THEMES,
        "weights": weights,
    }

    blob = json.dumps(payload, separators=(",", ":"))
    with open(args.out, "w") as handle:
        handle.write("// Generated by training/export_story.py - do not edit by hand.\n")
        handle.write(f"window.STORY = {blob};\n")
    size = os.path.getsize(args.out)
    print(f"wrote {args.out} ({size / 1024 / 1024:.1f} MB)")


if __name__ == "__main__":
    main()
