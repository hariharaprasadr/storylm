#!/usr/bin/env python3
"""Encode the engine corpus into the exact token stream the firmware will use.

The table in ``data/vocab.json`` (generated by ``make vocab``) is the only
vocabulary the model can ever emit: control tokens are matched exactly, words
are looked up by the same letters-only, lowercased rule as the C++
``normalize_word()``, and an unknown word is a hard error rather than a byte
fallback. That is what makes "every word has a narration asset" a property of
the model instead of a hope.

Output: a ``.npz`` with
  ids   int32 [n, ctx]  token ids, padded with <PAD>
  mask  bool  [n, ctx]  true where the loss applies (story tokens only)
  meta  int32 [3]       vocab_count, ctx, n_stories
  vocab_file  str       the table the ids index into, so nothing has to guess
"""
from __future__ import annotations

import argparse
import json
import re

import numpy as np

WORD_RE = re.compile(r"[a-z]+")
TAG_RE = re.compile(r"<[^>]+>")


def load_table(path):
    with open(path) as handle:
        table = json.load(handle)
    tokens = table["tokens"]
    return tokens, {token: i for i, token in enumerate(tokens)}


def encode_story(prompt, lines, ids, ctx):
    """Returns (ids, loss_mask); raises on any word outside the table."""
    out = [ids["<BOS>"]]
    for tag in TAG_RE.findall(prompt):
        if tag not in ids:
            raise KeyError(f"control token not in the table: {tag}")
        out.append(ids[tag])

    prompt_len = len(out)
    for line in lines:
        out.append(ids["<LINE>"])
        for word in WORD_RE.findall(line.lower()):
            if word not in ids:
                raise KeyError(f"word not in the table: {word!r} in {line!r}")
            out.append(ids[word])
        out.append(ids["</LINE>"])
    out.append(ids["<END>"])
    out.append(ids["<EOS>"])

    if len(out) > ctx:
        raise ValueError(f"sequence of {len(out)} tokens exceeds ctx={ctx}")

    mask = [False] * prompt_len + [True] * (len(out) - prompt_len)
    pad = ctx - len(out)
    return (out + [ids["<PAD>"]] * pad, mask + [False] * pad)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", default="data/processed/train.jsonl")
    ap.add_argument("--vocab", default="data/vocab.json")
    ap.add_argument("--out", default="data/processed/train.npz")
    ap.add_argument("--ctx", type=int, default=384)
    args = ap.parse_args()

    tokens, ids = load_table(args.vocab)
    rows = []
    with open(args.corpus) as handle:
        for line in handle:
            line = line.strip()
            if line:
                rows.append(json.loads(line))

    packed_ids = np.zeros((len(rows), args.ctx), dtype=np.int32)
    packed_mask = np.zeros((len(rows), args.ctx), dtype=bool)
    for i, row in enumerate(rows):
        seq, mask = encode_story(row["prompt"], row["lines"], ids, args.ctx)
        packed_ids[i] = seq
        packed_mask[i] = mask

    np.savez_compressed(
        args.out,
        ids=packed_ids,
        mask=packed_mask,
        meta=np.array([len(tokens), args.ctx, len(rows)], dtype=np.int32),
        # Which table the ids index into. Without it, a 3,589-id set cannot be
        # paired with confidence (v2 and v3 share that width), and training or
        # evaluation would read the wrong word.
        vocab_file=np.array(args.vocab),
    )
    lengths = packed_mask.sum(axis=1)
    print(f"stories     {len(rows)}")
    print(f"vocab       {len(tokens)} ids")
    print(f"ctx         {args.ctx}")
    print(
        "story len   min %d median %d max %d tokens"
        % (lengths.min(), int(np.median(lengths)), lengths.max())
    )
    print(f"wrote       {args.out}")


if __name__ == "__main__":
    main()
